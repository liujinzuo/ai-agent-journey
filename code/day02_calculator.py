"""Day2：命令行计算器（第一版）。

任务：从键盘读两个数字，一次性输出加、减、乘、除四个结果。

运行：python code/day02_calculator.py

示例效果：
    请输入第一个数字: 10
    请输入第二个数字: 3
    10.0 + 3.0 = 13.0
    10.0 - 3.0 = 7.0
    10.0 * 3.0 = 30.0
    10.0 / 3.0 = 3.3333333333333335

知识点：input() / float() / 变量 / 算术运算符 / f-string / print()
注意：Day2 还没学 if 判断和循环，所以这一版不做运算符选择，四个结果一起给。
"""

# TODO 1：用 input() 读第一个数字，存进变量 num1
num1 = input("请输入第一个数字: ")

# TODO 2：用 input() 读第二个数字，存进变量 num2
num2 = input("请输入第二个数字: ")

# TODO 3：input() 读到的是字符串，用 float() 转成数字
a = float(num1)
b = float(num2)

# TODO 4：用 f-string 输出四行结果
print(f"{a} + {b} = {a + b}")
print(f"{a} - {b} = {a - b}")
print(f"{a} * {b} = {a * b}")
print(f"{a} / {b} = {a / b}")

