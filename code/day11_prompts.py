# 用法：复制 [提示词 A] 整段 → 粘贴发送；再开新对话 → 复制 [提示词 B] 整段 → 粘贴发送

BAD_PROMPT = """帮我整理一下这些支出。
早餐 12 元，地铁 4 元，打车 38 元，书 59 元，咖啡 22 元，电影 45 元"""

GOOD_PROMPT = """你是财务助理。

任务：把下面 6 笔支出整理成表格。

约束：
- 不要任何解释和开场白
- 不要增加原数据里没有的项目

输出格式：Markdown 表格，两列，列名是「用途」「金额（元）」，金额保留两位小数。

数据：
早餐 12 元，地铁 4 元，打车 38 元，书 59 元，咖啡 22 元，电影 45 元"""


print("=" * 24, "[提示词 A：随手一句话]", "=" * 24)
print(BAD_PROMPT)
print()
print("=" * 24, "[提示词 B：四件套版]", "=" * 24)
print(GOOD_PROMPT)
print()
